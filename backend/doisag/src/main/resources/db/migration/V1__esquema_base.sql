-- ---------------------------------------------------------------
-- usuarios
-- ---------------------------------------------------------------

create table users (
    id bigint generated by default as identity,
    name varchar(255) not null,
    cpf varchar(255) unique,
    email varchar(255) not null unique,
    password varchar(255) not null,
    birth_date date,
    phone varchar(255),
    street varchar(255),
    number varchar(255),
    city varchar(255),
    state varchar(255),
    country varchar(255),
    active boolean not null default true,
    failed_login_attempts integer not null default 0,
    locked_until timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table admin (
    id bigint not null,
    primary key (id),
    constraint fk_admin_users foreign key (id) references users (id)
);

create table prescriber (
    id bigint not null,
    profession varchar(255),
    professional_code varchar(255) unique,
    registry_type varchar(255),
    registry_number varchar(255),
    primary key (id),
    unique (registry_type, registry_number),
    constraint fk_prescriber_users foreign key (id) references users (id)
);

create table patient (
    id bigint not null,
    prescriber_id bigint,
    primary key (id),
    constraint fk_patient_users foreign key (id) references users (id),
    constraint fk_patient_prescriber foreign key (prescriber_id) references prescriber (id)
);

create index idx_patient_prescriber on patient (prescriber_id);

