create table appointment (
    id bigint generated by default as identity,
    patient_id bigint not null,
    prescriber_id bigint not null,
    date_time timestamp(6) not null,
    duration_minutes integer not null default 60,
    modality varchar(255) check (modality in ('PRESENCIAL', 'REMOTA')),
    status varchar(255) check (status in ('AGENDADA', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA')),
    diagnosis TEXT,
    clinical_observation TEXT,
    therapeutic_plan TEXT,
    evolution TEXT,
    physical_exam TEXT,
    complementary_exams TEXT,
    blood_pressure varchar(255),
    weight float4,
    height integer,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint fk_appointment_patient foreign key (patient_id) references patient (id),
    constraint fk_appointment_prescriber foreign key (prescriber_id) references prescriber (id)
);

create index idx_appointment_patient on appointment (patient_id, date_time);
create index idx_appointment_prescriber on appointment (prescriber_id, date_time);

