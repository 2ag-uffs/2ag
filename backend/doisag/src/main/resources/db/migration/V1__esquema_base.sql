-- esquema base do 2ag
-- junta as antigas migracoes 1 a 8 numa so ja com as correcoes de integridade
-- nome email e senha obrigatorios e indice em toda chave estrangeira
-- conta com flag de ativa e controle de tentativas erradas de login
-- tabela de administrador pra conta q provisiona prescritor
