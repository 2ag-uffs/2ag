create table assigned_scale (
    id bigint generated by default as identity,
    patient_id bigint not null,
    prescriber_id bigint not null,
    scale_type varchar(255) not null check (scale_type in ('ESCALA_HAMILTON', 'ESCALA_PITTSBURGH',
        'MINI_EXAME_ESTADO_MENTAL', 'REGISTRO_DOR', 'REGISTRO_SONO', 'REGISTRO_TEA', 'ANAMNESE',
        'ACOMPANHAMENTO_SEMANAL')),
    status varchar(255) not null check (status in ('PENDENTE', 'CONCLUIDO')),
    assigned_date date not null,
    completed_date date,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint fk_assigned_scale_patient foreign key (patient_id) references patient (id),
    constraint fk_assigned_scale_prescriber foreign key (prescriber_id) references prescriber (id)
);

create index idx_assigned_scale_patient on assigned_scale (patient_id, status);
create index idx_assigned_scale_prescriber on assigned_scale (prescriber_id, status);

create table treatment_protocol (
    id bigint generated by default as identity,
    patient_id bigint not null,
    prescriber_id bigint not null,
    start_date date not null,
    end_date date not null,
    active boolean not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint fk_protocol_patient foreign key (patient_id) references patient (id),
    constraint fk_protocol_prescriber foreign key (prescriber_id) references prescriber (id)
);

create index idx_protocol_patient on treatment_protocol (patient_id, active);

create table protocol_item (
    id bigint generated by default as identity,
    protocol_id bigint not null,
    scale_type varchar(255) not null check (scale_type in ('ESCALA_HAMILTON', 'ESCALA_PITTSBURGH',
        'MINI_EXAME_ESTADO_MENTAL', 'REGISTRO_DOR', 'REGISTRO_SONO', 'REGISTRO_TEA', 'ANAMNESE',
        'ACOMPANHAMENTO_SEMANAL')),
    periodicity varchar(255) not null check (periodicity in ('SEMANAL', 'QUINZENAL', 'MENSAL')),
    primary key (id),
    constraint fk_protocol_item_protocol foreign key (protocol_id) references treatment_protocol (id)
);

create index idx_protocol_item_protocol on protocol_item (protocol_id);

