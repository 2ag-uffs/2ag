-- a correcao do paciente gravava por cima e o valor de antes se perdia (decisao de 14/11/2026, revisao das regras R4)
-- cada correcao guarda aqui a versao q ela substituiu, e a prescritora ve corrigida em dd/mm com o valor antigo
-- a tabela so recebe insercao, como a trilha, e as respostas vao como json igual na resposta de escala

create table scale_response_correction (
    id bigint generated by default as identity,
    scale_response_id bigint not null,
    corrected_at timestamp(6) not null,
    period_start date not null,
    period_end date not null,
    answers TEXT not null,
    score integer,
    score_band varchar(120),
    primary key (id),
    constraint ck_scale_response_correction_period check (period_end >= period_start),
    constraint fk_scale_response_correction_response foreign key (scale_response_id) references scale_response (id)
);

create index idx_scale_response_correction_response on scale_response_correction (scale_response_id);

create table anamnesis_correction (
    id bigint generated by default as identity,
    anamnesis_id bigint not null,
    corrected_at timestamp(6) not null,
    assessment_date date not null,
    answers TEXT not null,
    primary key (id),
    constraint fk_anamnesis_correction_anamnesis foreign key (anamnesis_id) references anamnesis (id)
);

create index idx_anamnesis_correction_anamnesis on anamnesis_correction (anamnesis_id);
