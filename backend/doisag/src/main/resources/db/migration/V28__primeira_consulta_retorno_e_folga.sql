-- primeira consulta e retorno com duracao propria e dias de folga do prescritor (RF10 e RF11)
-- a clinica respondeu q a primeira dura de 60 a 90 min e o retorno menos

-- a duracao q ja existia vira a do retorno e a primeira ganha coluna propria
alter table prescriber add column first_appointment_duration_minutes integer default 90 not null;
alter table prescriber add constraint ck_prescriber_first_appointment_duration
    check (first_appointment_duration_minutes between 15 and 240);

-- consulta antiga fica sem tipo
alter table appointment add column appointment_type varchar(20);
alter table appointment add constraint ck_appointment_type
    check (appointment_type in ('PRIMEIRA_CONSULTA', 'RETORNO'));

-- dia em q o prescritor n atende e some dos horarios livres
-- off_date e n day pq day eh palavra reservada no h2 dos testes
-- a regra de unico ja serve de indice pra chave estrangeira (ver V17)
create table prescriber_day_off (
    id bigint generated by default as identity,
    prescriber_id bigint not null,
    off_date date not null,
    primary key (id),
    constraint uq_prescriber_day_off unique (prescriber_id, off_date),
    constraint fk_prescriber_day_off_prescriber foreign key (prescriber_id) references prescriber (id)
);
