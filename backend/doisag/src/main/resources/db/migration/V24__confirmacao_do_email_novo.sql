-- troca do e-mail de acesso confirmada no endereco novo (issue 130)
-- o e-mail so muda qnd a pessoa abre o link q foi pro endereco novo
-- tabela propria: a de senha nova tem outras regras de cancelamento e de contagem

create table email_change (
    id bigint generated by default as identity,
    user_id bigint not null,
    new_email varchar(255) not null,
    token_hash varchar(64) not null unique,
    created_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    used_at timestamp(6),
    primary key (id),
    constraint fk_email_change_users foreign key (user_id) references users (id)
);

create index idx_email_change_user on email_change (user_id, created_at);
